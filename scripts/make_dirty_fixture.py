#!/usr/bin/env python3
"""Generate a synthetic leaked-credentials tree for tests and CI.

    python3 scripts/make_dirty_fixture.py [output_dir]

Nothing here is a real credential. Values are drawn from a fixed-seed PRNG so
consecutive runs are byte-identical, but no realistic-format secret is ever
committed to the repository - GitHub push protection would (correctly) reject
it, and bypassing that protection to commit a fake key is the wrong trade.

Prints the directory it wrote to, so callers can capture it:

    dirty=$(python3 scripts/make_dirty_fixture.py)
    python3 scanner.py "$dirty"
"""
from __future__ import annotations

import os
import random
import string
import sys

SEED = 20260101

B62 = string.ascii_letters + string.digits
HEX = "0123456789abcdef"
B64 = string.ascii_letters + string.digits + "+/"


def rnd(alphabet: str, n: int, rng: random.Random) -> str:
    return "".join(rng.choice(alphabet) for _ in range(n))


def build(rng: random.Random) -> dict[str, str]:
    """Return {relative_path: contents} for the fixture tree."""
    env = f"""# Synthetic credentials generated by scripts/make_dirty_fixture.py.
# Every value is random and none of them are live. Do not commit this file.
AWS_ACCESS_KEY_ID=AKIA{rnd(string.ascii_uppercase + string.digits, 16, rng)}
AWS_SECRET_ACCESS_KEY={rnd(B62, 40, rng)}
GITHUB_TOKEN=ghp_{rnd(B62, 36, rng)}
STRIPE_KEY=sk_live_{rnd(B62, 24, rng)}
SLACK_TOKEN=xoxb-{rnd(string.digits, 11, rng)}-{rnd(B62, 22, rng)}
GOOGLE_KEY=AIza{rnd(B62, 35, rng)}
DATABASE_PASSWORD="{rnd(HEX, 64, rng)}"
SESSION_KEY={rnd(HEX, 32, rng)}
"""
    app = f'''import os

# Synthetic values, not live credentials. Generated at test time.
api_key = "{rnd(B62, 33, rng)}"
TOKEN = "{rnd(B62, 32, rng)}"


def connect():
    return os.environ.get("api_key", api_key)
'''
    # Assembled from parts so the PEM header never appears as a literal in this
    # file; committing it would trip GitHub push protection on the generator.
    begin = "-" * 5 + "BEGIN PRIVATE KEY" + "-" * 5
    end = "-" * 5 + "END PRIVATE KEY" + "-" * 5
    key = begin + "\n" + "".join(rnd(B64, 64, rng) + "\n" for _ in range(3)) + end + "\n"
    compose = f"""services:
  api:
    environment:
      # synthetic, generated at test time
      JWT_SECRET: {rnd(B62, 43, rng)}
      REDIS_PASSWORD: {rnd(HEX, 40, rng)}
"""
    return {
        "config.env": env,
        "app.py": app,
        "id_ed25519": key,
        "docker-compose.yml": compose,
    }


def main(argv: list[str]) -> int:
    rng = random.Random(SEED)
    files = build(rng)
    out = argv[0] if argv else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".dirty-fixture")
    out = os.path.abspath(out)
    os.makedirs(out, exist_ok=True)
    for name, contents in files.items():
        with open(os.path.join(out, name), "w", encoding="utf-8") as fh:
            fh.write(contents)
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
